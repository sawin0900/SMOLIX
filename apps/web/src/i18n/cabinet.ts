import type { Locale } from './landing'

const LOCALE_KEY = 'smolix_locale'

export function readCabinetLocale(): Locale {
  try {
    const stored = localStorage.getItem(LOCALE_KEY)
    if (stored === 'ru' || stored === 'en') return stored
  } catch {
    /* ignore */
  }
  return 'ru'
}

export function writeCabinetLocale(locale: Locale) {
  try {
    localStorage.setItem(LOCALE_KEY, locale)
  } catch {
    /* ignore */
  }
}

